"""Manifest-backed access to the IRO sample ecosystem shipped with Reawarp.

The IRO packs are generated by eli_lab-math-cover-generator and used by
sonicpi_eli_lab. This module reads their manifests in place, validates relative
paths and optional SHA-256 hashes, and exposes typed asset records without
copying, renaming or rewriting source audio.
"""
from __future__ import annotations

import csv
import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterable

IRO_ROOT = Path(__file__).resolve().parents[3] / "samples" / "Iro"
DRUM_PACK = IRO_ROOT / "experimental-drum-kit-211"
SOUND_FX_PACK = IRO_ROOT / "sound-fx-211"
SOUND_LAB_PACK = IRO_ROOT / "sound-lab-211"


@dataclass(frozen=True, slots=True)
class IROAsset:
    asset_id: str
    path: Path
    relative_path: str
    role: str
    family: str
    pack: str
    articulation: str = ""
    sha256: str = ""
    sample_rate: int | None = None
    channels: int | None = None
    duration_seconds: float | None = None
    source_feature_index: int | None = None
    seed: int | None = None
    midi_note: int | None = None
    metadata: dict[str, Any] | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "asset_id": self.asset_id,
            "path": str(self.path),
            "relative_path": self.relative_path,
            "role": self.role,
            "family": self.family,
            "pack": self.pack,
            "articulation": self.articulation,
            "sha256": self.sha256,
            "sample_rate": self.sample_rate,
            "channels": self.channels,
            "duration_seconds": self.duration_seconds,
            "source_feature_index": self.source_feature_index,
            "seed": self.seed,
            "midi_note": self.midi_note,
            "metadata": self.metadata or {},
        }


def _safe_path(root: Path, relative_path: str) -> Path:
    candidate = (root / relative_path).resolve()
    base = root.resolve()
    if candidate != base and base not in candidate.parents:
        raise ValueError(f"IRO manifest path escapes pack root: {relative_path}")
    return candidate


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _load_json(path: Path) -> dict[str, Any] | None:
    if not path.is_file():
        return None
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError(f"IRO manifest must contain a JSON object: {path}")
    return payload


def _asset(
    *,
    pack_root: Path,
    relative_path: str,
    role: str,
    family: str,
    pack: str,
    articulation: str = "",
    expected_sha256: str = "",
    sample_rate: int | None = None,
    channels: int | None = None,
    duration_seconds: float | None = None,
    source_feature_index: int | None = None,
    seed: int | None = None,
    midi_note: int | None = None,
    metadata: dict[str, Any] | None = None,
) -> IROAsset:
    path = _safe_path(pack_root, relative_path)
    if not path.is_file():
        raise FileNotFoundError(f"IRO manifest references a missing asset: {path}")
    return IROAsset(
        asset_id=f"{pack}:{relative_path}",
        path=path,
        relative_path=relative_path.replace("\\", "/"),
        role=str(role),
        family=str(family or role),
        pack=pack,
        articulation=str(articulation or ""),
        sha256=str(expected_sha256 or ""),
        sample_rate=int(sample_rate) if sample_rate else None,
        channels=int(channels) if channels else None,
        duration_seconds=float(duration_seconds) if duration_seconds else None,
        source_feature_index=int(source_feature_index) if source_feature_index is not None else None,
        seed=int(seed) if seed is not None else None,
        midi_note=int(midi_note) if midi_note is not None else None,
        metadata=dict(metadata or {}),
    )


def load_drum_assets(*, verify_hashes: bool = False) -> list[IROAsset]:
    """Read the 96-hit experimental drum pack and its MIDI/articulation map."""
    manifest = _load_json(DRUM_PACK / "drum-kit-manifest.json")
    if manifest is None:
        return []
    drum_map = _load_json(DRUM_PACK / "drum-map.json") or {}
    midi_by_role: dict[str, int] = {}
    for instrument in drum_map.get("instruments", []):
        midi_by_role[str(instrument.get("name", ""))] = int(instrument.get("midi_note", 0))

    records: list[IROAsset] = []
    for item in manifest.get("assets", []):
        relative = str(item.get("file", ""))
        asset = _asset(
            pack_root=DRUM_PACK,
            relative_path=relative,
            role=str(item.get("role", "percussion")),
            family=str(item.get("family", item.get("role", "percussion"))),
            pack="experimental-drum-kit-211",
            articulation=str(item.get("articulation", "")),
            expected_sha256=str(item.get("sha256", "")),
            sample_rate=item.get("sample_rate"),
            duration_seconds=item.get("duration_seconds"),
            source_feature_index=item.get("source_feature_index"),
            seed=item.get("seed"),
            midi_note=midi_by_role.get(str(item.get("role", ""))),
            metadata={
                key: value for key, value in item.items()
                if key not in {"file", "role", "family", "articulation", "sha256",
                               "sample_rate", "duration_seconds", "source_feature_index", "seed"}
            },
        )
        if verify_hashes and asset.sha256 and _sha256(asset.path) != asset.sha256:
            raise ValueError(f"IRO SHA-256 mismatch: {asset.relative_path}")
        records.append(asset)
    return records


def load_sound_fx_assets(*, verify_hashes: bool = False) -> list[IROAsset]:
    """Read release-driven long events and loops without flattening families."""
    manifest = _load_json(SOUND_FX_PACK / "sound-fx-pack.json")
    if manifest is None:
        return []
    records: list[IROAsset] = []
    for item in manifest.get("event_families", []):
        relative = str(item.get("file", ""))
        if not relative:
            continue
        family_name = str(item.get("kind", item.get("name", "event_texture")))
        asset = _asset(
            pack_root=SOUND_FX_PACK,
            relative_path=relative,
            role="event_texture",
            family=family_name,
            pack="sound-fx-211",
            articulation=str(item.get("variant", "")),
            expected_sha256=str(item.get("sha256", "")),
            sample_rate=item.get("sample_rate"),
            channels=item.get("channels"),
            duration_seconds=item.get("duration_seconds"),
            source_feature_index=item.get("source_feature_index"),
            seed=item.get("seed"),
            metadata=dict(item),
        )
        if verify_hashes and asset.sha256 and _sha256(asset.path) != asset.sha256:
            raise ValueError(f"IRO SHA-256 mismatch: {asset.relative_path}")
        records.append(asset)

    for item in manifest.get("loops", []):
        relative = str(item.get("file", ""))
        if not relative:
            continue
        asset = _asset(
            pack_root=SOUND_FX_PACK,
            relative_path=relative,
            role="event_loop",
            family=str(item.get("kind", item.get("name", "event_loop"))),
            pack="sound-fx-211",
            expected_sha256=str(item.get("sha256", "")),
            sample_rate=item.get("sample_rate"),
            channels=item.get("channels"),
            duration_seconds=item.get("duration_seconds"),
            seed=item.get("seed"),
            metadata=dict(item),
        )
        if verify_hashes and asset.sha256 and _sha256(asset.path) != asset.sha256:
            raise ValueError(f"IRO SHA-256 mismatch: {asset.relative_path}")
        records.append(asset)
    return records

def load_sound_lab_assets(*, verify_hashes: bool = False) -> list[IROAsset]:
    """Read IRO one-shots, loops and stems from the compact sound-lab manifest."""
    manifest = _load_json(SOUND_LAB_PACK / "sound-pack.json")
    if manifest is None:
        return []
    records: list[IROAsset] = []
    for key, role in (("one_shots", "one_shot"), ("loops", "rendered_loop"), ("stems", "rendered_stem")):
        for item in manifest.get(key, []):
            relative = str(item.get("file", item.get("path", "")))
            if not relative:
                continue
            asset = _asset(
                pack_root=SOUND_LAB_PACK,
                relative_path=relative,
                role=role,
                family=str(item.get("family", item.get("name", role))),
                pack="sound-lab-211",
                expected_sha256=str(item.get("sha256", "")),
                sample_rate=item.get("sample_rate"),
                duration_seconds=item.get("duration_seconds"),
                seed=item.get("seed"),
                metadata=dict(item),
            )
            if verify_hashes and asset.sha256 and _sha256(asset.path) != asset.sha256:
                raise ValueError(f"IRO SHA-256 mismatch: {asset.relative_path}")
            records.append(asset)
    return records


def load_entity_assets(*, verify_hashes: bool = False) -> list[IROAsset]:
    """Read the eight mathematical entity families and their six variants."""
    entity_root = IRO_ROOT / "entities"
    records: list[IROAsset] = []
    if not entity_root.is_dir():
        return records
    for family_dir in sorted(entity_root.iterdir()):
        if not family_dir.is_dir():
            continue
        manifest = _load_json(family_dir / "family.json")
        if manifest is None:
            continue
        family = manifest.get("family", {})
        family_name = str(family.get("name", family_dir.name))
        for item in manifest.get("entities", []):
            relative = str(item.get("file", ""))
            asset = _asset(
                pack_root=IRO_ROOT,
                relative_path=relative,
                role="math_entity",
                family=family_name,
                pack="entities",
                articulation=str(item.get("variation", "")),
                expected_sha256=str(item.get("sha256", "")),
                sample_rate=item.get("sample_rate"),
                duration_seconds=item.get("duration_seconds"),
                source_feature_index=item.get("source_feature_index"),
                seed=item.get("seed"),
                metadata={
                    **dict(item),
                    "sonic_identity": family.get("sonic_identity", ""),
                    "synthesis_approach": family.get("synthesis_approach", ""),
                    "equation": family.get("equation", ""),
                },
            )
            if verify_hashes and asset.sha256 and _sha256(asset.path) != asset.sha256:
                raise ValueError(f"IRO SHA-256 mismatch: {asset.relative_path}")
            records.append(asset)
    return records


def load_iro_assets(*, verify_hashes: bool = False) -> list[IROAsset]:
    """Collect every supported IRO asset pack; preserve pack/family identity."""
    loaders = (load_drum_assets, load_sound_fx_assets, load_sound_lab_assets, load_entity_assets)
    result: list[IROAsset] = []
    for loader in loaders:
        result.extend(loader(verify_hashes=verify_hashes))
    return result


def resolve_iro_sample(
    role: str,
    *,
    family: str | None = None,
    articulation: str | None = None,
    variant: int | None = None,
    seed: int | str = 211,
) -> IROAsset:
    """Resolve an IRO drum asset deterministically by role and optional facets."""
    candidates = [
        item for item in load_drum_assets()
        if item.role == role
        and (family is None or item.family == family)
        and (articulation is None or item.articulation == articulation)
        and (variant is None or int((item.metadata or {}).get("variant", 0)) == variant)
    ]
    if not candidates:
        raise LookupError(
            f"No IRO drum asset matches role={role!r}, family={family!r}, "
            f"articulation={articulation!r}, variant={variant!r}"
        )
    payload = hashlib.sha256(f"reawarp:iro:{seed}:{role}".encode("utf-8")).digest()
    index = int.from_bytes(payload[:8], "little") % len(candidates)
    return candidates[index]


def verify_iro_assets(assets: Iterable[IROAsset] | None = None) -> dict[str, Any]:
    """Return an integrity report without modifying any shipped file."""
    selected = list(assets if assets is not None else load_iro_assets())
    missing: list[str] = []
    mismatched: list[str] = []
    unverified: list[str] = []
    verified = 0
    for item in selected:
        if not item.path.is_file():
            missing.append(item.relative_path)
            continue
        if not item.sha256:
            unverified.append(item.relative_path)
            continue
        if _sha256(item.path) != item.sha256:
            mismatched.append(item.relative_path)
        else:
            verified += 1
    return {
        "total": len(selected),
        "verified": verified,
        "unverified": unverified,
        "missing": missing,
        "mismatched": mismatched,
        "ok": not missing and not mismatched,
    }


def search_iro_assets(
    *,
    role: str | None = None,
    family: str | None = None,
    pack: str | None = None,
    query: str | None = None,
) -> list[IROAsset]:
    """Filter IRO assets while retaining their original hierarchical grouping."""
    needle = (query or "").strip().lower()
    result = []
    for item in load_iro_assets():
        if role and item.role != role:
            continue
        if family and item.family != family:
            continue
        if pack and item.pack != pack:
            continue
        if needle and needle not in " ".join(
            (item.relative_path, item.role, item.family, item.articulation, item.pack)
        ).lower():
            continue
        result.append(item)
    return result
